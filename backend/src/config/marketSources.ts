/**
 * Market data sources that postings may be imported from (docs/MARKET_INTELLIGENCE.md).
 *
 * A source is listed only after its licence has been read and it permits storing the fields
 * SkillBridge keeps (title, employer, location, dates, salary and the skills read from the text;
 * never the description itself). No real source is registered yet: the zero-cost audit
 * (docs/ZERO_COST_API_POLICY.md) found none verified, so real-market analytics stay unavailable
 * and only the clearly labelled synthetic fixture can be imported.
 */

export type MarketDataset = 'sourced' | 'synthetic_fixture';

export interface MarketSource {
  id: string;
  name: string;
  url: string;
  licence: string;
  attribution: string;
  dataset: MarketDataset;
  /** Date the licence and terms were last read, YYYY-MM-DD. */
  verifiedOn: string;
  /** How long imported postings may be kept, in days; null when the terms set no limit. */
  retentionDays: number | null;
}

export const SYNTHETIC_FIXTURE_SOURCE: MarketSource = {
  id: 'skillbridge-synthetic-fixture',
  name: 'SkillBridge synthetic fixture',
  url: 'https://github.com/ameer0508/Bridging-Skills-to-Careers-An-AI-Powered-Guidance-System',
  licence: 'Generated test data; not a job market',
  attribution: 'Synthetic data generated by SkillBridge for testing. It does not describe real jobs.',
  dataset: 'synthetic_fixture',
  verifiedOn: '2026-10-12',
  retentionDays: null,
};

const sources = new Map<string, MarketSource>([[SYNTHETIC_FIXTURE_SOURCE.id, SYNTHETIC_FIXTURE_SOURCE]]);

export const getMarketSource = (id: string): MarketSource | undefined => sources.get(id);

export const listMarketSources = (): MarketSource[] => [...sources.values()];

/**
 * Adds a source at runtime. Used by tests to exercise the sourced-data path; a real source is
 * added to the map above in a reviewed change that cites its licence.
 */
export function registerMarketSource(source: MarketSource): () => void {
  sources.set(source.id, source);
  return () => {
    sources.delete(source.id);
  };
}
